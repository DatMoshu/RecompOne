using System.Numerics;
using System.Text.Json;
using ImGuiNET;
using RecompOne.Runtime.Play;

namespace RecompOne.Runtime.Host.Window;

/// <summary>Quick-access UI over the existing <see cref="Savestate"/> mailbox
/// (SavePending/LoadPending, applied by the game host at its own safe frame boundary
/// -- see PE1's Patches.PerFrame). This panel never calls Capture/Restore directly;
/// it only sets the mailbox, so it can never apply a state at the wrong call depth
/// itself. Two things gate the normal Load button:
///  - version stamp (<see cref="Savestate.IsCurrentVersion"/>) -- a plain Savestate
///    file saved by a different build is shown as stale and refused;
///  - <see cref="SafeToLoadProbe"/>, an optional <c>Play.Probes</c> flag name a game
///    can register (e.g. PE1's "pe1.bookmarkSafe") so the button visibly declines
///    instead of silently queuing a load that the host will never find a safe frame
///    to apply (or worse, applies at the wrong depth and goes black).
///
/// Two on-disk formats can live in the slots directory -- a plain Savestate (magic
/// 0x52315353) and a Play.Bookmarks file (magic "R1BM", its own build-stamp check) --
/// see <see cref="Savestate.TryReadHeader"/> / <see cref="Bookmarks.IsBookmarkFile"/>.
/// Both are listed; do not assume a single magic when scanning.</summary>
public sealed class SavestatePanel : IPanel
{
    public string Name => "Savestates";
    public bool IsOpen { get; set; }

    // Directory to scan for *.sav slots. A game host points this wherever its state
    // library lives (default: next to the exe, matching Savestate.SlotPath's default).
    public static string SlotsDir = ".";
    // Optional Play.Probes flag name; null = no gating (always considered safe).
    public static string? SafeToLoadProbe;

    // manifest.json shaped as [{"file":"x.sav","label":"..."}] -- confirmed against the
    // PE1 state library (games/ParasiteEve/saves/states/), generated by another session.
    static Dictionary<string, string>? _labels;
    static DateTime _labelsStamp;

    string _newSlotName = "";
    // PROVISIONAL debug affordance, added at the user's explicit request: an operator
    // who wants to test load-at-arbitrary-points on purpose can tick this to unlock a
    // second, visually distinct button per slot that skips the safety gate entirely.
    // Remove this whole escape hatch (and Savestate.ForceLoadPending) once save/load at
    // an arbitrary point is properly supported.
    bool _forceArmed;

    public void Draw()
    {
        ImGui.SetNextWindowSize(new Vector2(460, 460), ImGuiCond.FirstUseEver);
        bool open = IsOpen;
        if (!ImGui.Begin(Name, ref open)) { IsOpen = open; ImGui.End(); return; }

        var mem = Runtime.Mem;
        bool safe = SafeToLoadProbe == null || (mem != null && Probes.TryFlag(SafeToLoadProbe, mem, out var v) && v);

        ImGui.TextDisabled($"Slots: {SlotsDir}");
        // Where F5 lands, stated outright. It was possible to be several hours into a session
        // with every manual save going somewhere the user never chose and could not see, so
        // the destination is now always on screen rather than inferable.
        ImGui.Text("F5 saves to:");
        ImGui.SameLine();
        ImGui.TextColored(new Vector4(0.55f, 0.85f, 1f, 1f), Savestate.SlotPath);
        if (AutoState.IsAutoState(Savestate.SlotPath))
        {
            ImGui.SameLine();
            ImGui.TextColored(new Vector4(1f, 0.4f, 0.4f, 1f), "(DISPOSABLE!)");
            if (ImGui.IsItemHovered())
                ImGui.SetTooltip("The manual slot is pointing at an automatic capture. Retention can\n" +
                                 "delete it. Use \"Save New\" to move your saves somewhere durable.");
        }
        ImGui.TextDisabled($"This is {(RunKind.IsHuman ? "a human" : "an agent")} run; its automatic captures go to {AutoState.Dir}/.");
        if (!safe)
            ImGui.TextColored(new Vector4(1f, 0.6f, 0.2f, 1f), "Not at a safe point to load right now (mid-FMV/menu/loading).");

        ImGui.Separator();
        ImGui.InputText("##newslot", ref _newSlotName, 64);
        ImGui.SameLine();
        if (ImGui.Button("Save New") && _newSlotName.Length > 0)
        {
            Directory.CreateDirectory(SlotsDir);
            Savestate.SlotPath = Path.Combine(SlotsDir, _newSlotName + ".sav");
            Savestate.SavePending = true;
            _newSlotName = "";
        }

        ImGui.Separator();
        ImGui.Checkbox("Enable Force Load (debug/unsafe)", ref _forceArmed);
        ImGui.TextWrapped(
            "Force Load skips the safety gate and applies on the very next frame no matter " +
            "what is happening right now. Loading outside a safe point can black-screen or " +
            "corrupt the running game: restoring memory and registers cannot redirect which " +
            "native code is currently executing, so whatever was mid-FMV/menu/loading just " +
            "keeps running against RAM it no longer recognizes. Debug-only, provisional -- " +
            "to be removed if this can't be fixed properly.");

        ImGui.Separator();

        if (!Directory.Exists(SlotsDir))
        {
            ImGui.TextDisabled("(directory does not exist yet)");
            IsOpen = open; ImGui.End();
            return;
        }

        var labels = LoadLabels();
        foreach (var path in Directory.EnumerateFiles(SlotsDir, "*.sav").OrderBy(p => p))
        {
            // Two formats can live here (plain Savestate, magic 0x52315353; Bookmarks,
            // magic "R1BM"). Anything matching neither isn't ours at all (e.g. carda.sav/
            // cardb.sav, the PS1 memory-card images that conventionally live next to the
            // exe too) and is skipped outright rather than mislabeled stale.
            bool isPlainState = Savestate.TryReadHeader(path, out var isState, out _) && isState;
            bool isBookmark = !isPlainState && Bookmarks.IsBookmarkFile(path);
            if (!isPlainState && !isBookmark) continue;

            var file = Path.GetFileName(path);
            // Staleness is now a BUILD-STAMP question, read straight off the file for either
            // format (StateLoad.Classify), not a format-version one. Two reasons that
            // matters here: a v1/v2 state is perfectly readable and should not be shown as
            // stale, and -- more usefully -- a real mismatch can now say WHICH half moved.
            // A game-only rebuild moves no PS1-side address and is the routine case worth
            // overriding; an engine rebuild can change what captured HLE state means.
            var match = StateLoad.Classify(path);
            bool current = match is StampMatch.Same or StampMatch.Unknown;
            string kindTag = isBookmark ? " (bookmark)" : "";
            string label = (labels?.GetValueOrDefault(file) ?? Path.GetFileNameWithoutExtension(file)) + kindTag;

            ImGui.PushID(path);
            ImGui.TextUnformatted(label);
            ImGui.SameLine();
            // MANUAL vs AUTO is the distinction that matters most in this list: one is
            // something a person chose to keep, the other is deleted on a timer. They were
            // previously indistinguishable here, so a disposable file could look like a save.
            bool auto = AutoState.IsAutoState(path);
            ImGui.TextColored(auto ? new Vector4(0.7f, 0.7f, 0.7f, 1f) : new Vector4(0.5f, 0.9f, 0.5f, 1f),
                              auto ? "[AUTO]" : "[MANUAL]");
            ImGui.SameLine();
            ImGui.TextDisabled(Describe(path));
            if (string.Equals(Path.GetFullPath(path), SafeFullPath(Savestate.SlotPath),
                              StringComparison.OrdinalIgnoreCase))
            {
                ImGui.SameLine();
                ImGui.TextColored(new Vector4(0.55f, 0.85f, 1f, 1f), "<- F5 slot");
            }
            if (!current)
            {
                ImGui.SameLine();
                // Colour carries the risk ranking: a game-only rebuild is amber (usually
                // fine, override freely), anything touching the engine is red.
                var tint = match == StampMatch.GameOnly
                    ? new Vector4(1f, 0.75f, 0.25f, 1f)
                    : new Vector4(1f, 0.4f, 0.4f, 1f);
                ImGui.TextColored(tint, match == StampMatch.GameOnly ? "GAME REBUILT" : "ENGINE REBUILT");
            }
            ImGui.SameLine();

            bool canLoad = current && safe;
            if (!canLoad) ImGui.BeginDisabled();
            if (ImGui.SmallButton("Load"))
            {
                // BootLoadPath, NOT SlotPath. Loading is a READ; making it silently repoint
                // the F5 destination is what fed an hour of a person's manual saves into the
                // autostate pool, where retention deleted them. Where you load from and where
                // you save to are different questions and the UI must not conflate them.
                Savestate.BootLoadPath = path;
                Savestate.LoadPending = true;
            }
            if (!canLoad) ImGui.EndDisabled();
            if (!current && ImGui.IsItemHovered())
                ImGui.SetTooltip($"Refusing to load: {BuildStamp.Explain(match)}.\n\n" +
                                 "Use Force Load below to override anyway.");
            else if (!safe && ImGui.IsItemHovered())
                ImGui.SetTooltip("Not at a safe frame to apply a load right now.");

            ImGui.SameLine();
            // Saving DOES repoint the slot -- that is what the button means. It refuses only
            // for a disposable file: a manual save aimed into the autostate pool is deleted
            // by retention without warning, which is exactly how saves were lost before.
            bool disposable = AutoState.IsAutoState(path);
            if (disposable) ImGui.BeginDisabled();
            if (ImGui.SmallButton("Save Here")) { Savestate.SlotPath = path; Savestate.SavePending = true; }
            if (disposable) ImGui.EndDisabled();
            if (disposable && ImGui.IsItemHovered())
                ImGui.SetTooltip("This is an automatic capture. Saving into it would put your save in the\n" +
                                 "disposable pool, where retention deletes it. Use \"Save New\" above instead.");

            ImGui.SameLine();
            if (!_forceArmed) ImGui.BeginDisabled();
            ImGui.PushStyleColor(ImGuiCol.Button, new Vector4(0.55f, 0.12f, 0.12f, 1f));
            ImGui.PushStyleColor(ImGuiCol.ButtonHovered, new Vector4(0.75f, 0.15f, 0.15f, 1f));
            if (ImGui.SmallButton("Force Load (unsafe)"))
            {
                // Force Load means force EVERYTHING: the safety gate (ForceLoadPending) and
                // the build-stamp refusal. Anyone who ticked the arming checkbox above has
                // already read what this does; being refused by a second, quieter gate after
                // that would just look broken.
                StateLoad.Force = true;
                Savestate.BootLoadPath = path;   // read-only source; see the Load button above
                Savestate.ForceLoadPending = true;
            }
            ImGui.PopStyleColor(2);
            if (!_forceArmed) ImGui.EndDisabled();
            if (ImGui.IsItemHovered())
                ImGui.SetTooltip("Bypasses the safety gate entirely. May black-screen or corrupt the running game.");
            ImGui.PopID();
        }

        DrawAutoStates(safe);

        IsOpen = open;
        ImGui.End();
    }

    // Automatic captures (Host/AutoState.cs) live in their own directory and are pruned to
    // the newest few as the run goes on. They are listed separately, and labelled, so nobody
    // has to wonder whether one of these is something they saved and meant to keep: everything
    // in this section is disposable by design and will be deleted by retention on its own.
    static void DrawAutoStates(bool safe)
    {
        // BOTH directories, always, each labelled with whose they are. Hiding the other run
        // kind's captures would trade one invisible-state problem for another: the point of
        // the split is that an agent cannot DELETE the user's states, not that either side
        // gets a secret folder the other cannot see.
        foreach (var dir in new[] { AutoState.Dir, "autostates", "autostates_agent" }
                     .Distinct(StringComparer.OrdinalIgnoreCase))
            DrawAutoStateDir(dir, safe);
    }

    static void DrawAutoStateDir(string dir, bool safe)
    {
        if (!Directory.Exists(dir)) return;

        var files = new DirectoryInfo(dir)
            .GetFiles($"{AutoState.Prefix}*.sav")
            .OrderByDescending(f => f.LastWriteTimeUtc)
            .ToList();
        if (files.Count == 0) return;

        bool mine = string.Equals(dir, AutoState.Dir, StringComparison.OrdinalIgnoreCase);
        string whose = string.Equals(dir, "autostates_agent", StringComparison.OrdinalIgnoreCase)
            ? "agent runs" : "human play";

        ImGui.Separator();
        ImGui.PushID(dir);
        if (!ImGui.CollapsingHeader($"Automatic (disposable) - {whose} - {files.Count} kept###{dir}"))
        { ImGui.PopID(); return; }
        ImGui.TextDisabled($"{dir}/ - written by {whose}{(mine ? ", including this run" : "")}.");
        ImGui.TextDisabled($"Captured every {AutoState.IntervalFrames / 60.0:0.#}s; only the newest {AutoState.Keep} are kept.");

        // This is the list the crash/fix/resume loop actually uses, so it is also where the
        // build-stamp override has to be reachable: after a fix-and-rebuild EVERY auto-state
        // here mismatches by construction (the fix is what invalidated them), and almost
        // always by the harmless half -- the game assembly. Say which half, and give a way
        // through, rather than greying the whole list out with the word "stale".
        foreach (var f in files)
        {
            var match = StateLoad.Classify(f.FullName);
            bool current = match is StampMatch.Same or StampMatch.Unknown;
            ImGui.PushID(f.FullName);
            ImGui.TextUnformatted($"{f.Name}   {f.LastWriteTime:HH:mm:ss}  ({Age(f.LastWriteTimeUtc)} ago)");
            if (!current)
            {
                ImGui.SameLine();
                var tint = match == StampMatch.GameOnly
                    ? new Vector4(1f, 0.75f, 0.25f, 1f)
                    : new Vector4(1f, 0.4f, 0.4f, 1f);
                ImGui.TextColored(tint, match == StampMatch.GameOnly ? "GAME REBUILT" : "ENGINE REBUILT");
                if (ImGui.IsItemHovered()) ImGui.SetTooltip(BuildStamp.Explain(match));
            }
            ImGui.SameLine();
            bool canLoad = current && safe;
            if (!canLoad) ImGui.BeginDisabled();
            if (ImGui.SmallButton("Load"))
            {
                Savestate.BootLoadPath = f.FullName; // read-only source, never the F5 target
                Savestate.LoadPending = true;
            }
            if (!canLoad) ImGui.EndDisabled();
            // "Load anyway" waits for the SAFE FRAME like a normal load (it sets LoadPending,
            // not ForceLoadPending) and overrides only the build-stamp refusal. Those are two
            // independent gates and conflating them is how a load lands mid-cutscene.
            if (!current)
            {
                ImGui.SameLine();
                if (!safe) ImGui.BeginDisabled();
                if (ImGui.SmallButton("Load anyway"))
                {
                    StateLoad.Force = true;
                    Savestate.BootLoadPath = f.FullName; // read-only source
                    Savestate.LoadPending = true;
                }
                if (!safe) ImGui.EndDisabled();
                if (ImGui.IsItemHovered())
                    ImGui.SetTooltip("Override the build-stamp refusal (still waits for a safe frame).\n" +
                                     BuildStamp.Explain(match));
            }
            ImGui.PopID();
        }
        ImGui.PopID();
    }

    /// <summary>Time, age and size for one state file -- the things you actually need to
    /// tell two candidates apart. A filename and a build stamp were not enough: picking the
    /// right save out of a list meant launching them one at a time to see where they were.</summary>
    static string Describe(string path)
    {
        try
        {
            var fi = new FileInfo(path);
            return $"{fi.LastWriteTime:HH:mm:ss}  ({Age(fi.LastWriteTimeUtc)} ago)  {fi.Length / (1024.0 * 1024.0):0.0} MB";
        }
        catch { return ""; }
    }

    static string Age(DateTime utc)
    {
        var t = DateTime.UtcNow - utc;
        return t.TotalMinutes < 1 ? $"{t.TotalSeconds:F0}s"
             : t.TotalHours < 1 ? $"{t.TotalMinutes:F0}m"
             : t.TotalDays < 1 ? $"{t.TotalHours:F1}h"
             : $"{t.TotalDays:F1}d";
    }

    /// <summary>GetFullPath that cannot throw -- SlotPath is user-settable and a malformed
    /// value must not take the whole panel down mid-frame.</summary>
    static string SafeFullPath(string p)
    {
        try { return Path.GetFullPath(p); } catch { return p; }
    }

    static Dictionary<string, string>? LoadLabels()
    {
        var manifestPath = Path.Combine(SlotsDir, "manifest.json");
        if (!File.Exists(manifestPath)) return null;
        var stamp = File.GetLastWriteTimeUtc(manifestPath);
        if (_labels != null && stamp == _labelsStamp) return _labels;
        try
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath));
            var map = new Dictionary<string, string>();
            foreach (var entry in doc.RootElement.EnumerateArray())
            {
                if (entry.TryGetProperty("file", out var f) && entry.TryGetProperty("label", out var l))
                    map[f.GetString() ?? ""] = l.GetString() ?? "";
            }
            _labels = map;
            _labelsStamp = stamp;
        }
        catch { _labels = null; }
        return _labels;
    }
}
